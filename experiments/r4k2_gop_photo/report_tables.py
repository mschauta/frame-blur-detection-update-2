"""The full R4K-2 tables: data/results.json -> tables.md (standard library only).

usage: python experiments/r4k2_gop_photo/report_tables.py
"""
import collections
import csv
import gzip
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "data" / "results.json").read_text(encoding="utf-8"))
MO = (("static", "static"), ("pan", "pan"))
RA = (("crf23", "CRF 23"), ("crf28", "CRF 28"), ("crf33", "CRF 33"), ("2mbps", "2 Mbit/s"))
CELLS = (("I", "I"), ("IP", "I"), ("IP", "P"), ("IPB", "I"), ("IPB", "P"), ("IPB", "B"))
pct = lambda x: f"{x * 100:.1f}"


def ci(x, s=1.0, d=1, sign=True):
    f = (lambda v: f"{v * s:+.{d}f}") if sign else (lambda v: f"{v * s:.{d}f}")
    return f"{f(x['value'])} [{f(x['ci95'][0])}, {f(x['ci95'][1])}]"


out = ["# R4K-2: full tables", "", "Generated by `report_tables.py` from `data/results.json`. Percentages of frames; "
       "intervals are 95% bootstrap intervals over the photos (2000 resamples, seed 20261028).", ""]
out.append("**Quality: mean PSNR (dB) by structure and frame type**\n")
out.append("| motion, rate | I only | IP: I | IP: P | IPB: I | IPB: P | IPB: B |\n|---|---|---|---|---|---|---|")
for mo, mon in MO:
    for ra, ran in RA:
        out.append(f"| {mon}, {ran} | " + " | ".join(f"{r['quality'][f'{mo}/{ra}/{s}/{t}']['psnr_mean']:.1f}" for s, t in CELLS) + " |")
out.append("\n**Mean coded size (bytes)**\n")
out.append("| motion, rate | I only | IP: I | IP: P | IPB: I | IPB: P | IPB: B |\n|---|---|---|---|---|---|---|")
for mo, mon in MO:
    for ra, ran in RA:
        out.append(f"| {mon}, {ran} | " + " | ".join(f"{r['quality'][f'{mo}/{ra}/{s}/{t}']['pkt_size_mean']:,.0f}" for s, t in CELLS) + " |")
for m, mn, cs in (("base", "round3 Base", ("r95", "r98")), ("small", "round3 Small", ("r95", "r98")), ("v9", "v9", ("r95", "M>0"))):
    for c in cs:
        out.append(f"\n**False alarms (% of frames), {mn}, {c if c != 'M>0' else 'M > 0'}**\n")
        out.append("| motion, rate | I only | IP: I | IP: P | IPB: I | IPB: P | IPB: B |\n|---|---|---|---|---|---|---|")
        for mo, mon in MO:
            for ra, ran in RA:
                out.append(f"| {mon}, {ran} | " + " | ".join(pct(r['false_alarms'][f'{m}/{c}/{mo}/{ra}/{s}/{t}']['value']) for s, t in CELLS) + " |")
P = r["paired_vs_I_only"]
for m, mn in (("base", "round3 Base"), ("small", "round3 Small")):
    out.append(f"\n**Paired difference against the I-only coding, {mn}: logit**\n")
    out.append("| motion, rate | IP: I | IP: P | IPB: I | IPB: P | IPB: B |\n|---|---|---|---|---|---|")
    for mo, mon in MO:
        for ra, ran in RA:
            out.append(f"| {mon}, {ran} | " + " | ".join(ci(P[f'{m}/{mo}/{ra}/{s}/{t}']['score_difference'], d=1) for s, t in CELLS[1:]) + " |")
for m, mn in (("base", "round3 Base"), ("small", "round3 Small"), ("v9", "v9")):
    out.append(f"\n**Paired difference against the I-only coding, {mn}: share called blurred at r95 (percentage points)**\n")
    out.append("| motion, rate | IP: I | IP: P | IPB: I | IPB: P | IPB: B |\n|---|---|---|---|---|---|")
    for mo, mon in MO:
        for ra, ran in RA:
            out.append(f"| {mon}, {ran} | " + " | ".join(ci(P[f'{m}/{mo}/{ra}/{s}/{t}']['blurred_share_difference_r95'], 100, 1) for s, t in CELLS[1:]) + " |")
R = r["r4k1_repeat"]
for st, note in (("IPB", "the protocol's measure"), ("IP", "added, beyond the protocol")):
    out.append(f"\n**The in-clip I-frame is the lowest of its triple (%), {st} clips ({note}); null = the same positions coded I-only**\n")
    out.append("| model, motion | " + " | ".join(ran for _, ran in RA) + " |\n|---|---|---|---|---|")
    for m, mn in (("base", "round3 Base"), ("small", "round3 Small"), ("v9", "v9")):
        for mo, mon in MO:
            cells = []
            for ra, _ in RA:
                v = R[f"{m}/{mo}/{ra}/{st}"]
                t = f", ties {pct(v['tied']['value'])}" if v["tied"]["value"] > 0.005 else ""
                cells.append(f"{pct(v['i_frame_sharpest']['value'])}{t} (null {pct(v['null_I_only_same_positions']['value'])}); diff {ci(v['difference'], 100, 1)}")
            out.append(f"| {mn}, {mon} | " + " | ".join(cells) + " |")
Q = r["quality_matched"]
out.append("\n**At equal quality: P/B frames minus I-only frames in the same 1 dB PSNR bin, weighted by the P/B count**\n")
out.append("| model | static | pan |\n|---|---|---|")
for m, mn, d, s in (("base", "round3 Base (logit)", 1, 1), ("small", "round3 Small (logit)", 1, 1), ("v9", "v9 (M)", 4, 1)):
    out.append(f"| {mn} | " + " | ".join(ci(Q[f'{m}/{mo}']['weighted_difference_pb_minus_I_only'], 1, d) for mo, _ in MO) + " |")
w = Q["base/static"]["weighted_difference_pb_minus_I_only"]
out.append(f"\nMatched bins hold {w['pb_frames_in_matched_bins']:,} of {w['pb_frames']:,} static P/B frames and "
           f"{Q['base/pan']['weighted_difference_pb_minus_I_only']['pb_frames_in_matched_bins']:,} of {Q['base/pan']['weighted_difference_pb_minus_I_only']['pb_frames']:,} pan P/B frames.\n")
out.append("**Per bin, round3 Base: mean logit of the P/B frames / of the I-only frames**\n")
out.append("| PSNR bin | static: P/B | static: I only | pan: P/B | pan: I only |\n|---|---|---|---|---|")
bs = {b["psnr_bin"]: b for b in Q["base/static"]["bins"]}
bp = {b["psnr_bin"]: b for b in Q["base/pan"]["bins"]}
for k in sorted(set(bs) | set(bp)):
    a, b = bs.get(k), bp.get(k)
    f = lambda x, key: f"{x[key]:.1f}" if x else "–"
    out.append(f"| {k} dB | {f(a, 'mean_pb')} | {f(a, 'mean_I_only')} | {f(b, 'mean_pb')} | {f(b, 'mean_I_only')} |")

# descriptive, not a measure of the protocol: how the false alarms spread over the photos (from data/frames.csv.gz)
per = collections.defaultdict(collections.Counter)
cols = {"base": "base_logit", "small": "small_logit", "v9": "v9_m"}
with gzip.open(HERE / "data" / "frames.csv.gz", "rt", newline="", encoding="utf-8") as fh:
    for row in csv.DictReader(fh):
        for m, col in cols.items():
            for c, t in r["thresholds"][m].items():
                s = float(row[col])
                if (s > t) if m == "v9" else (s >= t):
                    per[(m, c)][row["photo"]] += 1
out.append("\n**How the false alarms spread over the photos** (descriptive, not a measure of the protocol)\n")
out.append("| model, threshold | false alarms (of 115,200 frames) | photos with any (of 100) | share of the 5 photos with most |\n"
           "|---|---|---|---|")
for m, mn in (("base", "round3 Base"), ("small", "round3 Small"), ("v9", "v9")):
    for c in r["thresholds"][m]:
        cnt = per[(m, c)]
        tot = sum(cnt.values())
        top = sum(v for _, v in cnt.most_common(5))
        out.append(f"| {mn}, {c if c != 'M>0' else 'M > 0'} | {tot:,} | {len(cnt)} | {100 * top / max(tot, 1):.0f}% |")
(HERE / "tables.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(HERE / "tables.md")
